export function computeScores(answers: number[]): number[] {
  const scores = new Array(TYPE_KEYS.length).fill(0)
  answers.forEach((optIdx, qIdx) => {
    if (optIdx < 0) return
    const weights = QUESTIONS[qIdx].options[optIdx].weights
    weights.forEach((w, j) => {
      scores[j] += w
    })
  })
  return scores
}

export function getWinner(scores: number[]): string {
  let maxS = -1
  let winner = 0
  scores.forEach((s, i) => {
    if (s > maxS) {
      maxS = s
      winner = i
    }
  })
  return TYPE_KEYS[winner]
}
